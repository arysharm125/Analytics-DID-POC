@router.post("/record_report", responses={**APITokenDep401Response, **bad_request_response(), **conflict_response(_ADVISORY_DIVISION)})
async def record_report(request: RecordReportRequest, api_token: AdvisoryTokenDep, did_svc: DIDServiceDep) -> RecordReportResponse:
    """Record an advisory report as a DID.

    Creates a new Digital Artefact record or a new version of an existing one.
    The report must reference a valid recommendation artefact via recommendation_uid.
    If the artefact_id already exists, the request must include at least one
    change to artefact_hash, artefact_metadata, or provenance - otherwise a
    400 Bad Request error is returned.
    """

    # Validate that recommendation_uid exists and is of type "recommendation" in advisory division
    recommendation = did_svc.find_artefact_by_uid_and_type(
        uid=request.recommendation_uid,
        division=division_from_str(_ADVISORY_DIVISION),
        artefact_type=artefact_type_from_str("recommendation")
    )

    if recommendation is None:
        raise RecommendationNotFoundError(request.recommendation_uid)

    # Build artefact input from request with recommendation_uid as provenance
    artefact_input = ArtefactInput(
        external_uid=request.report_uid,
        division=_ADVISORY_DIVISION,
        artefact_hash=request.artefact_hash,
        artefact_metadata=request.artefact_metadata,
        artefact_type="report",  # Advisory reports are always type "report"
        backlink=request.backlink,
        provenance=[request.recommendation_uid],  # Set provenance to the recommendation
        update_message=request.update_message,
        updated_by=request.updated_by,
    )

    # Upsert the artefact
    record = did_svc.upsert_artefact(artefact_input)

    return RecordReportResponse(
        artefact_did=did_from_uuid(record.external_uid),
        version_did=did_from_uuid(record.version_uid),
        version=record.version,
    )

@router.get("/did.json")
async def advisory_did(did_svc: DIDServiceDep):
    """Return the DID document that corresponds to the advisory division.

    This DID document contains the keys that are used to verify digital artefacts
    associated with the advisory division.

    Returns:
        JSON-LD DID Document.
    """
    return did_svc.division_did_doc(_ADVISORY_DIVISION)


@router.get("/{uid}/vc.json", responses={**APITokenDep401Response, **not_found_response()})
async def artefact_vc(
    uid: PathUUID,
    api_token: AdvisoryTokenDep,
    did_svc: DIDServiceDep,):
    """Return a Verifiable Credential with proofs for a Digital Artefact."""
    return did_svc.issue_artefact_vc(division=_ADVISORY_DIVISION, uid=uid)
