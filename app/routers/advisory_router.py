_ADVISORY_DIVISION = "advisory"

router = APIRouter(tags=["Advisory API"], prefix="/advisory")
logger = logging.getLogger("advisory_api")

_example_random_uuid = f"{uuid4()}"

class RecordRecommendationRequest(ArtefactFieldsMixin):
    artefact_uid: UUIDString = Field(
        ...,  # Required
        description="Globally unique ID of this recommendation (must be a valid UUID)",
        json_schema_extra={"example": _example_random_uuid},
        examples=[_example_random_uuid],
    )

    # Override artefact_metadata with more specific description
    artefact_metadata: dict[str, Any] | None = Field(
        default=None,
        alias="artefact_metadata",
        description="An object with properties set by the caller (corresponds to metadata about the artefact)",
        json_schema_extra={"example": {"platform": "cloud", "provider": "AWS"}},
    )


class RecordRecommendationResponse(BaseModel):
    artefact_did: AMDWebDID = Field(
        description="""The DID generated by the system for the artefact. This may
        not be unique if the same artefact_id is reused multiple times (each time
        generates a new internal version of the DID).""",
        examples=[f"did:web:did.amd.com:{_example_random_uuid}"],
    )
    version_did: AMDWebDID = Field(
        description="""The DID generated for the specific version created by the request.""",
        examples=["did:web:did.amd.com:b8ff3b79-863f-4fa9-84ba-0067663f2b04"],
    )
    version: int = Field(
        description="""The version number of the DID, if multiple versions of the same
        artefact were created. Starts at 1.""",
        examples=[1, 18],
    )


@router.post("/record_recommendation", responses={**APITokenDep401Response, **bad_request_response(), **conflict_response(_ADVISORY_DIVISION)})
async def record_recommendation(request: RecordRecommendationRequest, api_token: AdvisoryTokenDep, did_svc: DIDServiceDep) -> RecordRecommendationResponse:
    """Record an advisory recommendation as a DID.

    Creates a new Digital Artefact record of type 'recommendation' or a new version of an existing one.
    If the artefact_uid already exists, the request must include at least one
    change to artefact_hash, artefact_metadata, or provenance - otherwise a
    400 Bad Request error is returned.
    """

    # Build artefact input from request
    artefact_input = ArtefactInput(
        external_uid=request.artefact_uid,
        division=_ADVISORY_DIVISION,
        artefact_hash=request.artefact_hash,
        artefact_metadata=request.artefact_metadata,
        artefact_type="recommendation",  # Advisory recommendations are always type "recommendation"
        backlink=request.backlink,
        provenance=request.provenance,
        update_message=request.update_message,
        updated_by=request.updated_by,
    )

    # Upsert the artefact
    record = did_svc.upsert_artefact(artefact_input)

    return RecordRecommendationResponse(
        artefact_did=did_from_uuid(record.external_uid),
        version_did=did_from_uuid(record.version_uid),
        version=record.version,
    )


